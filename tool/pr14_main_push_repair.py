EXPECTED_SOURCE_PRODUCT_RUN_ID = 30974509667
EXPECTED_SOURCE_PRODUCT_RUN_ATTEMPT = 1
REPOSITORY = "alex00Pirotskyi/kris.ai"


def verify_source_product_run(
    run: Mapping[str, Any],
    jobs_payload: Mapping[str, Any],
    *,
    transcript: Transcript,
) -> None:
    expected = {
        "id": EXPECTED_SOURCE_PRODUCT_RUN_ID,
        "name": "product-gates",
        "event": "pull_request",
        "status": "completed",
        "conclusion": "success",
        "head_branch": STATUS_BRANCH,
        "head_sha": EXPECTED_TRIGGER_HEAD,
        "run_attempt": EXPECTED_SOURCE_PRODUCT_RUN_ATTEMPT,
    }
    for key, value in expected.items():
        require(
            run.get(key) == value,
            f"source product run {key} mismatch: {run.get(key)!r} != {value!r}",
        )
    require(
        (run.get("head_repository") or {}).get("full_name") == REPOSITORY,
        "source product run repository mismatch",
    )
    pull_numbers = {row.get("number") for row in (run.get("pull_requests") or [])}
    require(
        EXPECTED_TRIGGER_PR in pull_numbers,
        "source product run does not reference exact trigger PR",
    )

    jobs = jobs_payload.get("jobs") or []
    required = {"validate-ubuntu", "validate-windows", "validate-macos"}
    observed_names = {row.get("name") for row in jobs}
    require(observed_names == required, f"unexpected source product job set: {sorted(observed_names)}")
    for name in sorted(required):
        matches = [row for row in jobs if row.get("name") == name]
        require(len(matches) == 1, f"source product job count mismatch for {name}: {len(matches)}")
        row = matches[0]
        require(row.get("status") == "completed", f"source product job not completed: {name}")
        require(row.get("conclusion") == "success", f"source product job not successful: {name}")
        transcript.write(
            f"SOURCE_PRODUCT_JOB={name} ID={row.get('id')} CONCLUSION=success"
        )


