def validate_candidate_scope(transcript: Transcript, target: pathlib.Path) -> None:
    changed = sorted(
        filter(
            None,
            command_output(transcript, ("git", "diff", "--name-only"), cwd=target).splitlines(),
        )
    )
    transcript.write(f"CHANGED_PATHS={json.dumps(changed)}")
    require(tuple(changed) == AUTHORIZED_PATHS, f"candidate scope mismatch: {changed}")

    ci_value = (target / CI_PATH).read_text(encoding="utf-8")
    require(
        ci_value.count(f"      - name: {BOOTSTRAP_STEP_NAME}\n") == 1,
        "bootstrap step count mismatch",
    )
    require(
        ci_value.count(f"        run: {BOOTSTRAP_COMMAND}\n") == 1,
        "bootstrap command count mismatch",
    )
    doc_value = (target / DOC_PATH).read_text(encoding="utf-8")
    for marker in (
        "**Human roadmap authority:** `docs/roadmap/MASTER.md`",
        "## Challenges passed",
        "protected `main`",
        f"Authorizing product run:** `{EXPECTED_SOURCE_PRODUCT_RUN_ID}`",
    ):
        require(marker in doc_value, f"candidate document marker missing: {marker}")


def construct_candidate(
    transcript: Transcript,
    target: pathlib.Path,
    *,
    control_sha: str,
) -> tuple[str, bool]:
    apply_ci_bootstrap(target / CI_PATH)
    doc_path = target / DOC_PATH
    doc_path.parent.mkdir(parents=True, exist_ok=True)
    doc_path.write_text(
        candidate_document(control_sha),
        encoding="utf-8",
        newline="\n",
    )

    commands: Iterable[Sequence[str]] = (
        (sys.executable, "tool/p2_refresh_source_manifest.py", "."),
        (sys.executable, "tool/p2_source_inventory_test.py", "--project", "."),
        (
            sys.executable,
            "tool/p2_shared_p1_authority_contract_test.py",
            "--project",
            ".",
            "--owner-risk-qa",
        ),
        (sys.executable, "tool/v71r12_bootstrap_hosted_python.py", "--project", "."),
        (sys.executable, "tool/integration_train_test.py", "--project", "."),
        (sys.executable, "tool/p1_exit_gate_test.py", "--project", "."),
        (sys.executable, "tool/p0_003_repair_test.py"),
        (sys.executable, "tool/p0_008_roadmap_test.py", "--project", "."),
        (
            sys.executable,
            "tool/roadmap_control.py",
            "validate",
            "--project",
            ".",
            "--strict",
        ),
        (sys.executable, "tool/p0_010_generated_state_test.py", "--project", "."),
        ("git", "diff", "--check"),
    )
    for command in commands:
        run_command(transcript, command, cwd=target)

    validate_candidate_scope(transcript, target)
    run_command(
        transcript,
        ("git", "config", "user.name", "Kristin CI Repair"),
        cwd=target,
    )
    run_command(
        transcript,
        (
            "git",
            "config",
            "user.email",
            "41898282+github-actions[bot]@users.noreply.github.com",
        ),
        cwd=target,
    )
    run_command(transcript, ("git", "add", *AUTHORIZED_PATHS), cwd=target)
    run_command(transcript, ("git", "diff", "--cached", "--check"), cwd=target)
    run_command(
        transcript,
        (
            "git",
            "commit",
            "-m",
            "fix(ci): bootstrap P1 closure and document PR14 recovery",
        ),
        cwd=target,
    )
    candidate = git_output(transcript, target, "rev-parse", "HEAD")
    parent = git_output(transcript, target, "rev-parse", "HEAD^")
    require(parent == EXPECTED_TARGET_HEAD, f"candidate parent mismatch: {parent}")

    push = run_command(
        transcript,
        ("git", "push", "origin", f"{candidate}:refs/heads/{TARGET_BRANCH}"),
        cwd=target,
        check=False,
    )
    if push.returncode == 0:
        remote = git_output(
            transcript,
            target,
            "ls-remote",
            "origin",
            f"refs/heads/{TARGET_BRANCH}",
        )
        remote_sha = remote.split()[0] if remote else ""
        require(remote_sha == candidate, f"target ref verification mismatch: {remote_sha}")
        return candidate, True

    output = push.stdout or ""
    require(
        any(marker in output for marker in KNOWN_WORKFLOW_PUSH_REJECTIONS),
        "target push failed for an unrecognized reason",
    )
    transcript.write("REPAIR_OBJECT_TRANSFERRED_FOR_CONNECTED_REF_UPDATE=true")
    return candidate, False


def execute(control: pathlib.Path, target: pathlib.Path, status: pathlib.Path) -> int:
    transcript = Transcript()
    repair_rc = 1
    error = "candidate construction did not start"
    candidate = ""
    ref_updated = False

    repository = os.environ.get("GITHUB_REPOSITORY", "")
    event_name = os.environ.get("GITHUB_EVENT_NAME", "")
    ref = os.environ.get("GITHUB_REF", "")
    control_sha = os.environ.get("CONTROL_SHA", "")
    workflow_run_id = os.environ.get("GITHUB_RUN_ID", "")
    workflow_run_attempt = os.environ.get("GITHUB_RUN_ATTEMPT", "")
    source_run_id = os.environ.get("SOURCE_PRODUCT_RUN_ID", "")
    source_run_attempt = os.environ.get("SOURCE_PRODUCT_RUN_ATTEMPT", "")

    try:
        require(repository == REPOSITORY, f"repository mismatch: {repository!r}")
        require(event_name == "push", f"event mismatch: {event_name!r}")
        require(ref == "refs/heads/main", f"ref mismatch: {ref!r}")
        require(len(control_sha) == 40, "CONTROL_SHA is invalid")
        require(workflow_run_id.isdigit(), "GITHUB_RUN_ID is invalid")
        require(workflow_run_attempt.isdigit(), "GITHUB_RUN_ATTEMPT is invalid")
        require(
            source_run_id == str(EXPECTED_SOURCE_PRODUCT_RUN_ID),
            f"source run ID mismatch: {source_run_id!r}",
        )
        require(
            source_run_attempt == str(EXPECTED_SOURCE_PRODUCT_RUN_ATTEMPT),
            f"source run attempt mismatch: {source_run_attempt!r}",
        )

        verify_checkout(transcript, control, expected_head=control_sha)
        verify_checkout(
            transcript,
            status,
            expected_head=EXPECTED_TRIGGER_HEAD,
            expected_branch=STATUS_BRANCH,
        )
        verify_checkout(
            transcript,
            target,
            expected_head=EXPECTED_TARGET_HEAD,
            expected_branch=TARGET_BRANCH,
        )
        remote_target = git_output(transcript, target, "rev-parse", f"origin/{TARGET_BRANCH}")
        require(remote_target == EXPECTED_TARGET_HEAD, f"remote target mismatch: {remote_target}")

        api_env = os.environ.copy()
        pull = load_json_command(
            transcript,
            ("gh", "api", f"repos/{repository}/pulls/{EXPECTED_TRIGGER_PR}"),
            cwd=control,
            env=api_env,
        )
        verify_trigger_pr(pull, repository)
        run = load_json_command(
            transcript,
            (
                "gh",
                "api",
                f"repos/{repository}/actions/runs/{EXPECTED_SOURCE_PRODUCT_RUN_ID}",
            ),
            cwd=control,
            env=api_env,
        )
        jobs = load_json_command(
            transcript,
            (
                "gh",
                "api",
                f"repos/{repository}/actions/runs/{EXPECTED_SOURCE_PRODUCT_RUN_ID}/jobs?per_page=100",
            ),
            cwd=control,
            env=api_env,
        )
        verify_source_product_run(run, jobs, transcript=transcript)
        candidate, ref_updated = construct_candidate(
            transcript,
            target,
            control_sha=control_sha,
        )
        repair_rc = 0
        error = ""
    except Exception as exc:
        error = f"{type(exc).__name__}: {exc}"
        transcript.write(error)
        transcript.write(traceback.format_exc().rstrip())

    payload = receipt_payload(
        repair_rc=repair_rc,
        error=error,
        source_run_id=EXPECTED_SOURCE_PRODUCT_RUN_ID,
        source_run_attempt=EXPECTED_SOURCE_PRODUCT_RUN_ATTEMPT,
        control_sha=control_sha,
        candidate=candidate,
        ref_updated=ref_updated,
        workflow_run_id=workflow_run_id,
        workflow_run_attempt=workflow_run_attempt,
    )
    try:
        publish_receipt(transcript, status, payload)
    except Exception as exc:
        transcript.write(f"RECEIPT_PUBLISH_FAILURE={type(exc).__name__}: {exc}")
        transcript.write(traceback.format_exc().rstrip())
        return 1
    return 0 if repair_rc == 0 and candidate else 1


def self_test() -> int:
    with tempfile.TemporaryDirectory(prefix="pr14-main-push-self-test-") as raw:
        root = pathlib.Path(raw)
        ci = root / "ci.yml"
        ci.write_text(
            "name: product-gates\n"
            "jobs:\n"
            "  validate:\n"
            "    steps:\n"
            "      - run: flutter pub get\n"
            "\n"
            "      - name: Capture CI environment\n"
            "        run: true\n",
            encoding="utf-8",
            newline="\n",
        )
        apply_ci_bootstrap(ci)
        value = ci.read_text(encoding="utf-8")
        require(value.count(BOOTSTRAP_STEP_NAME) == 1, "self-test bootstrap name mismatch")
        require(value.count(BOOTSTRAP_COMMAND) == 1, "self-test bootstrap command mismatch")

        doc = candidate_document("a" * 40)
        for marker in (
            "docs/roadmap/MASTER.md",
            "## Challenges passed",
            "protected `main`",
            str(EXPECTED_SOURCE_PRODUCT_RUN_ID),
        ):
            require(marker in doc, f"self-test document marker missing: {marker}")

        run = {
            "id": EXPECTED_SOURCE_PRODUCT_RUN_ID,
            "name": "product-gates",
            "event": "pull_request",
            "status": "completed",
            "conclusion": "success",
            "head_branch": STATUS_BRANCH,
            "head_sha": EXPECTED_TRIGGER_HEAD,
            "run_attempt": EXPECTED_SOURCE_PRODUCT_RUN_ATTEMPT,
            "head_repository": {"full_name": REPOSITORY},
            "pull_requests": [{"number": EXPECTED_TRIGGER_PR}],
        }
        jobs = {
            "jobs": [
                {"id": index, "name": name, "status": "completed", "conclusion": "success"}
                for index, name in enumerate(
                    ("validate-ubuntu", "validate-windows", "validate-macos"),
                    start=1,
                )
            ]
        }
        verify_source_product_run(run, jobs, transcript=Transcript())
    print("PR14 protected-main push repair self-test: PASS")
    return 0


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--control", type=pathlib.Path)
    parser.add_argument("--target", type=pathlib.Path)
    parser.add_argument("--status", type=pathlib.Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if not args.self_test:
        missing = [
            name
            for name in ("control", "target", "status")
            if getattr(args, name) is None
        ]
        if missing:
            parser.error(f"missing required execution paths: {', '.join(missing)}")
    return args


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    if args.self_test:
        return self_test()
    return execute(
        args.control.resolve(),
        args.target.resolve(),
        args.status.resolve(),
    )


if __name__ == "__main__":
    raise SystemExit(main())
